def _num(s):
    return float(s.replace(",", ""))


def _size(text):
    m = re.search(r"(\d[\d,\.]*)\s*(million|mn|m)?\s*(?:-|\s)?(?:sq\.?\s?ft|square[- ]f(?:ee|oo)t|sf\b)", text, re.I)
    if m:
        return int(_num(m.group(1)) * (1_000_000 if m.group(2) else 1)), m.group(0).strip()
    m = re.search(r"(\d[\d,\.]*)\s*(萬)?\s*(?:平方呎|方呎|呎)", text)
    if m:
        return int(_num(m.group(1)) * (10_000 if m.group(2) else 1)), m.group(0).strip()
    return None, ""


def _floors(text):
    m = re.search(r"\b(\d{1,2}|two|three|four|five|six|seven|eight|nine|ten)\s+(?:and a half\s+)?(?:full\s+|whole\s+|entire\s+|office\s+)?floors\b", text, re.I)
    if m:
        g = m.group(1).lower()
        return int(g) if g.isdigit() else WORDNUM[g], m.group(0)
    m = re.search(r"(\d{1,2}|[一兩二三四五六七八九十])\s*(?:個)?(?:層|樓層)", text)
    if m:
        g = m.group(1)
        return int(g) if g.isdigit() else WORDNUM[g], m.group(0)
    return None, ""


def _company(title, lang, known):
    """Tenant named in the headline. Empty when unclear - never guessed."""
    tenants = [c for c, _, landlord in known if not landlord]
    if tenants:
        return tenants[0]
    if lang == "en":
        m = COMPANY_EN.match(title)
        if m:
            c = re.split(r"\s+(?:says|said|as|after|while)\s+|,\s*", m.group(1))[-1].strip(" ,:'’\"")
            c = re.sub(r"^(?:EXCLUSIVE|Exclusive)\s*\|?\s*", "", c)
            bad = (len(c.split()) > 6 or re.match(r"^(?:hong kong|hk)\b", c, re.I) or area_for(c)
                   or re.search(r"\b(?:site|building|office|shop|store|tower|market|landlords?|tenants?|firms?|companies|"
                                r"developers?|investors?|bidders?)\b", c, re.I))
            if c and not bad:
                return c
    else:
        for rx in COMPANY_ZH:
            m = rx.search(title)
            if m:
                c = m.group(1).strip()
                generic = re.search(r"超級|升級|多家|業內|機構|首|兼|大舉|再度|巨頭|全港|市場|公司|集團|商廈|寫字樓|業主|發展商|基金|年約|年前|香港|本港", c)
                if not generic and not area_for(c):
                    return c
    return ""


def _keys(item):
    t = item["title"]
    keys = {w.lower() for w in re.findall(r"[A-Z][A-Za-z0-9&'\-]{2,}", t)} - STOP
    keys |= {"n:" + n.replace(",", "") for n in re.findall(r"\d[\d,]{3,}", t)}
    return keys


