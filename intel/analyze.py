def build_property(raw_items, today, days=90):
    cutoff = today - dt.timedelta(days=days)
    seen_urls, seen_titles, items = set(), set(), []
    for r in raw_items:
        if not r.get("date") or r["date"] < cutoff or r["date"] > today + dt.timedelta(days=1):
            continue
        tnorm = re.sub(r"\W", "", r["title"].lower())
        if r["url"] in seen_urls or tnorm in seen_titles:
            continue
        seen_urls.add(r["url"]); seen_titles.add(tnorm)

        title = re.sub(r"\s*\(\d{1,2}:\d{2}\).*$|\s+-\s+\d{8}\s+-.*$", "", r["title"]).strip()
        # Hong Kong only, inbound only, no commentary / exits / residential / shops
        if NON_HK.search(title) and not HK.search(title) and not area_for(title):
            continue
        if OUTBOUND_RX.search(title) or NOISE_RX.search(title) or EXIT_RX.search(title) or EXCLUDE_RX.search(title):
            continue
        if not (HK.search(title) or area_for(title) or HK_PUBLISHERS.search(r["publisher"] + " " + r["publisher_url"])):
            continue
        types = [n for n, rx in TYPES_RX if rx.search(title)]
        if not types or not OFFICE_RX.search(title):
            continue
        if SHOP_ONLY_RX.search(title) and not re.search(r"office|headquarter|寫字樓|甲廈|總部|商廈", title, re.I):
            continue  # a shop / retail lease, not an office move-in
        if "Self-use purchase" not in types and \
                re.search(r"\bbuys?\b|acquir|\bsells?\b|\bsold\b|購入|沽|易手|成交", title, re.I) and \
                not re.search(r"headquarter|總部|relocat|搬遷", title, re.I):
            continue  # investment sale, not an occupier moving in

        known = companies_in(title)
        company = _company(title, r["lang"], known)
        building, b_area = building_for(title)
        if building in NON_OFFICE_BUILDINGS:
            building, b_area = None, None
        area = b_area or area_for(title) or AREA_UNSTATED
        size, size_txt = _size(title)
        floors, floors_txt = _floors(title)
        secs = [s for c, s, landlord in known if not landlord]
        secs += [s for s in sectors_for(title) if s not in ("Other", "Retail & Consumer")]
        secs = list(dict.fromkeys(secs)) or ["Facility Management & Real Estate"]
        items.append({
            "title": title, "url": r["url"], "date": r["date"], "publisher": r["publisher"] or r["feed"],
            "lang": r["lang"], "types": types, "building": building or "", "area": area,
            "size": size, "size_txt": size_txt, "floors": floors, "floors_txt": floors_txt, "sectors": secs,
            "company": company, "grade_a_text": bool(GRADE_A_RX.search(title)),
            "entities": {c for c, _, landlord in known if not landlord},
            "landlords": [c for c, _, landlord in known if landlord],
        })

    # --- corroboration: cluster reports of the same move (across languages/outlets)
    for it in items:
        it["_keys"] = _keys(it)
    parent = list(range(len(items)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i in range(len(items)):
        for j in range(i + 1, len(items)):
            a, b = items[i], items[j]
            gap = abs((a["date"] - b["date"]).days)
            if gap > 21:
                continue
            if AREA_UNSTATED not in (a["area"], b["area"]) and a["area"] != b["area"]:
                continue
            same_ent = bool(a["entities"] & b["entities"])
            same_co = bool(a["company"]) and a["company"].lower() == b["company"].lower()
            same_bld = bool(a["building"]) and a["building"] == b["building"]
            same_ll = bool(set(a["landlords"]) & set(b["landlords"]))
            same_size = bool(a["size"]) and a["size"] == b["size"]
            shared = a["_keys"] & b["_keys"]
            if ((same_ent or same_co) and gap <= 14) or (same_bld and (same_ll or same_size) and gap <= 10) or len(shared) >= 3:
                parent[find(i)] = find(j)

    clusters = {}
    for i, it in enumerate(items):
        clusters.setdefault(find(i), []).append(it)

    out = []
    for group in clusters.values():
        group.sort(key=lambda x: (x["lang"] != "en",
                                  not (x["company"] and x["title"].lower().find(x["company"].split()[0].lower()) in (0, 1, 2)),
                                  -(bool(x["size"]) + bool(x["building"]) + bool(x["company"])), x["date"]))
        p = group[0]
        company = p["company"] or next((g["company"] for g in group if g["company"]), "")
        if not company:
            continue  # nobody to call: not actionable
        building = p["building"] or next((g["building"] for g in group if g["building"]), "")
        landlords = list(dict.fromkeys(l for g in group for l in g["landlords"]))
        publishers = sorted({g["publisher"] for g in group})
        types = list(dict.fromkeys(t for g in group for t in g["types"]))
        secs = list(dict.fromkeys(s for g in group for s in g["sectors"]))
        if len(secs) > 1 and secs[0] == "Facility Management & Real Estate":
            secs = secs[1:] + secs[:1]
        size = max((g["size"] for g in group if g["size"]), default=None)
        floors = max((g["floors"] for g in group if g["floors"]), default=None)
        size_txt = next((g["size_txt"] for g in group if g["size"] == size), "") if size else ""
        floors_txt = next((g["floors_txt"] for g in group if g["floors"] == floors), "") if floors else ""
        area = p["area"] if p["area"] != AREA_UNSTATED else next(
            (g["area"] for g in group if g["area"] != AREA_UNSTATED), AREA_UNSTATED)
        if building:
            grade = "Grade A building (named)"
        elif any(g["grade_a_text"] for g in group):
            grade = "Grade A (per report)"
        elif area in PRIME_AREAS:
            grade = "Prime office district"
        else:
            grade = "Not stated"

        score, reasons = 0, []

        def add(n, why):
            nonlocal score
            score += n
            reasons.append(f"{why} (+{n})")

        if "New HQ" in types: add(3, "New headquarters fit-out")
        if "Relocation" in types or "Lease / pre-lease" in types: add(2, "Move-in: new premises need security systems")
        if "Expansion" in types: add(2, "Expansion: extra floors to secure")
        if "Self-use purchase" in types: add(2, "Owner-occupier purchase: full building security")
        if types == ["New office"]: add(1, "New office opening")
        if grade.startswith("Grade A building"): add(2, f"Grade A building: {building}")
        elif grade.startswith("Grade A"): add(2, "Grade A office (per report)")
        elif grade == "Prime office district": add(1, f"Prime office district: {area}")
        if size:
            if size >= 50_000: add(3, f"Large space ({size:,} sq ft)")
            elif size >= 20_000: add(2, f"Mid-size space ({size:,} sq ft)")
            elif size >= 5_000: add(1, f"{size:,} sq ft")
        if floors:
            if floors >= 5: add(2, f"{floors} floors")
            elif floors >= 2: add(1, f"{floors} floors")
        if any(s in secs for s in ("Finance & Professional Services", "Data Centre", "Luxury & HNW Goods")):
            add(2, "High-security tenant (finance / legal / luxury / data)")
        elif any(s in secs for s in ("AI & Technology", "Healthcare & Life Sciences")):
            add(1, "Tech / healthcare tenant: access control & IP protection")
        if len(publishers) >= 2: add(1, f"Reported by {len(publishers)} outlets")

        verification = f"Corroborated by {len(publishers)} outlets" if len(publishers) >= 2 else "Single outlet: open source to confirm"
        who, pitch = play(secs[0])
        place = building or (area if area != AREA_UNSTATED else "their new Hong Kong office")
        if "Expansion" in types:
            timing = "Expansion: offer to extend and unify their CCTV and access control across the new floors."
        elif types == ["New office"]:
            timing = "New office: offer the SME bundle (access control + intruder alarm + SOC remote viewing)."
        else:
            timing = "Move-in: security design is usually fixed during fit-out planning, so reach them before the fit-out tender."
        actions = [
            f"Find {company}'s workplace / facilities / office-admin lead in Hong Kong (links below).",
            (f"Call {', '.join(landlords)} leasing / building management at {place} for the fit-out timeline, contractor and consultant."
             if landlords else f"Call the building management office at {place} for the fit-out timeline and contractor."),
            timing,
            f"Pitch: {pitch}.",
            "Update Status here after each contact so the team can see progress.",
        ]

        out.append({
            "id": _id("pr", re.sub(r"\W", "", p["title"].lower())[:80], p["date"]), "kind": "property",
            "headline": p["title"], "date": max(g["date"] for g in group).isoformat(),
            "first_reported": min(g["date"] for g in group).isoformat(),
            "month": max(g["date"] for g in group).strftime("%Y-%m"),
            "company": company, "types": types, "type": types[0], "building": building, "landlords": landlords,
            "area": area, "grade": grade, "sectors": secs, "sector": secs[0],
            "size": size, "size_txt": size_txt, "floors": floors, "floors_txt": floors_txt, "lang": p["lang"],
            "who": who, "pitch": pitch, "actions": actions, "links": _links(company),
            "sources": [{"name": g["publisher"], "url": g["url"], "title": g["title"], "date": g["date"].isoformat()}
                        for g in sorted(group, key=lambda g: g["date"])],
            "verification": verification, "score": score, "level": _level(score, 8, 5), "thresholds": [8, 5], "reasons": reasons,
        })
    return out


