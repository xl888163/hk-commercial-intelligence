def _id(*parts):
    return hashlib.sha1("|".join(str(p) for p in parts).encode()).hexdigest()[:12]


def _level(score, high, med):
    return "HIGH" if score >= high else "MEDIUM" if score >= med else "LOW"


def _fmt(d):
    return f"{d.day} {d.strftime('%b %Y')}"


