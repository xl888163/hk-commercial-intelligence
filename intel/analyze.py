"""Turn raw source items into actionable sales records.

No fabrication:
  * every record keeps the original headline/name and a link to its source;
  * facts (company, building, size, dates, organiser contacts) are filled only
    when present in the source text, otherwise left empty ("Not stated");
  * the rating, "who to meet", pitch and next actions are Securitas sales
    guidance generated by rules - labelled as such, never presented as fact.
"""
