ACCESS_MAP = {
    "trade": "Trade only",
    "public": "Public",
    "trade and public": "Trade & public",
    "by registration": "By registration",
    "by invitation": "Invitation only",
}
INVITE_RX = re.compile(r"by invitation|invitation[- ]only|invite[- ]only|closed[- ]door|members[- ]only|"
                       r"private (?:dinner|roundtable|briefing|reception)|VIP only", re.I)
ONLINE_RX = re.compile(r"\bvirtual\b|webinar|online|zoom", re.I)
SENIOR_RX = re.compile(r"summit|forum|luncheon|town hall|\bCEO\b|chairman|leaders|dialogue|roundtable|reception|"
                       r"conference|congress|general assembly|\bweek\b|business summit|ball\b|visit to", re.I)
TRAINING_RX = re.compile(r"\[[^\]]*skills\]|workshop|masterclass|\bcourse\b|training|seminar cum|how to", re.I)
LEISURE_RX = re.compile(r"ballet|halloween|spooktacular|wine tasting|yoga|\brun\b|hike|movie night|glasses", re.I)

EVENT_SECTOR_PTS = {
    "Data Centre": 5, "Facility Management & Real Estate": 4, "Security & Safety": 5,
    "Finance & Professional Services": 3, "Infrastructure & Construction": 3, "Logistics & Supply Chain": 3,
    "Retail & Consumer": 3, "Luxury & HNW Goods": 5, "Healthcare & Life Sciences": 2,
    "Education & Government": 2, "Hospitality, Food & Tourism": 2, "AI & Technology": 1,
    "Energy & Environment": 1, "Manufacturing & Consumer Goods": 1,
}


def _access(raw):
    a = (raw.get("access") or "").strip()
    if a.lower() in ACCESS_MAP:
        return ACCESS_MAP[a.lower()]
    if INVITE_RX.search(" ".join([raw["name"], raw.get("description", ""), raw.get("category", "")])):
        return "Invitation / members only"
    return a or "Not stated in listing"


def _months(start, end):
    out, y, m = [], start.year, start.month
    while (y, m) <= (end.year, end.month) and len(out) < 13:
        out.append(f"{y:04d}-{m:02d}")
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


def build_events(raw_events, today):
    month_start = today.replace(day=1)
    horizon = today + dt.timedelta(days=366)
    kept = []
    for r in raw_events:
        if not r.get("start") or r["end"] < today or r["start"] > horizon:
            continue  # only events a salesperson can still attend
        if re.search(r"\bconcert\b|\blive\b|\btour\b|fan ?meeting|halloween|comedy|symphony|\bcon\b", r["name"], re.I):
            continue
        if NON_HK.search(f"{r.get('venue', '')} {r['name']}") and not HK.search(r.get("venue", "")) \
                and not area_for(r.get("venue", "")):
            continue
        kept.append(r)

    merged = []
    for r in sorted(kept, key=lambda e: (e["start"], e["name"])):
        norm = re.sub(r"[^a-z0-9]", "", r["name"].lower().replace("2026", "").replace("2027", ""))
        for m in merged:
            if m["start"] == r["start"] and difflib.SequenceMatcher(None, m["_norm"], norm).ratio() > 0.75:
                m["sources"].append({"name": r["source"], "url": r["url"]})
                for k in ("venue", "organiser", "contact_phone", "contact_email", "organiser_url"):
                    if not m.get(k) and r.get(k):
                        m[k] = r[k]
                break
        else:
            merged.append(dict(r, _norm=norm, sources=[{"name": r["source"], "url": r["url"]}]))

    out = []
    for r in merged:
        text = " ".join([r["name"], r.get("category", ""), r.get("description", ""), r.get("organiser", "")])
        secs = sectors_for(text)
        relevant = [s for s in secs if s in EVENT_SECTOR_PTS]
        primary = max(relevant, key=lambda s: EVENT_SECTOR_PTS[s]) if relevant else secs[0]
        access = _access(r)
        venue = r.get("venue") or ""
        online = bool(ONLINE_RX.search(f"{venue} {r.get('category', '')} {r['name']}"))
        area = "Online / Virtual" if online else (area_for(venue) or area_for(r["name"]) or AREA_UNSTATED)
        big_venue = "HKCEC" in venue or "AsiaWorld-Expo" in venue
        days = (r["end"] - r["start"]).days + 1
        is_fair = big_venue and bool(re.search(r"trade|exhibition|fair|expo|show|festival", f"{access} {r.get('category', '')} {r['name']}", re.I))

        score, reasons, leads = 0, [], []

        def add(n, why):
            nonlocal score
            score += n
            reasons.append(f"{why} ({'+' if n >= 0 else ''}{n})")

        if relevant:
            add(EVENT_SECTOR_PTS[primary], f"Buyers in a Securitas sector: {primary}")
            leads.append("Prospect networking")
            if len(relevant) >= 2:
                add(1, "Several target sectors present")
        if primary == "Security & Safety":
            leads.append("Partner & market intel")
        if "Luxury & HNW Goods" in secs:
            leads.append("HNW clients & artwork protection")
        partner = is_fair or "exhibition" in r.get("category", "").lower() or "fair" in r["name"].lower()
        if partner and primary in ("Data Centre", "Luxury & HNW Goods", "Security & Safety", "Infrastructure & Construction",
                                   "Facility Management & Real Estate"):
            add(1, "Exhibitors / organiser are potential partners")
            leads.append("Exhibitor & organiser partnership")
        if SENIOR_RX.search(r["name"]) and not TRAINING_RX.search(r["name"]):
            add(2, "Senior decision-makers in the room")
            leads.append("Senior networking")
        if access in ("Invitation only", "Invitation / members only"):
            add(2, "Invitation-only: exclusive access to decision-makers")
        elif access == "Trade only":
            add(1, "Trade-only: B2B buyers, not consumers")
        if is_fair:
            add(1, "Large trade exhibition: many exhibitors to prospect")
        if "Trade Development Council" in r.get("organiser", "") or r["name"].startswith("HKTDC"):
            add(1, "HKTDC flagship fair")
        security_lead = big_venue and days >= 2 and access in ("Public", "Trade & public")
        if security_lead:
            add(2, "Public event at a major venue: event-security lead for the organiser")
            leads.append("Event-security lead")
        if online:
            add(-2, "Online only: limited networking")
        if TRAINING_RX.search(r["name"]):
            add(-2, "Training / skills session: few buyers")
        if LEISURE_RX.search(r["name"]):
            add(-1, "Social / leisure format")

        if score < 3:
            continue  # not directly actionable for sales

        who, pitch = play(primary)
        if security_lead and not relevant:
            who, pitch = EVENT_SECURITY

        # --- next actions (sales guidance)
        reg_by = r["start"] - dt.timedelta(days=7)
        reg_txt = f"by {_fmt(reg_by)}" if reg_by >= today else "now (event is close)"
        if access in ("Invitation only", "Invitation / members only"):
            step1 = f"Request an invitation from the organiser {reg_txt}; check if a client or partner can bring you."
        elif "Chamber" in access:
            step1 = f"Book through the chamber {reg_txt} (member rate if Securitas is a member)."
        elif access == "Trade only":
            step1 = f"Register as a trade visitor on the organiser's site {reg_txt}; bring business cards and a MySecuritas demo."
        else:
            step1 = f"Register / plan attendance {reg_txt}."
        steps = [step1]
        if is_fair:
            steps.append(f"Before the fair, shortlist exhibitors and visitors from: {who}. Book 3-5 meetings.")
        else:
            steps.append(f"Target in the room: {who}.")
        steps.append(f"Pitch: {pitch}.")
        if security_lead:
            contact = " / ".join(x for x in (r.get("contact_phone"), r.get("contact_email")) if x)
            org = r.get("organiser") or "the organiser"
            steps.append(f"Event-security lead: contact {org}" + (f" ({contact}, as listed by HKCEC)" if contact else "")
                         + " about guarding, crowd management and badge control for this or the next edition.")
        if "Exhibitor & organiser partnership" in leads:
            steps.append(f"Partnership: ask {r.get('organiser') or 'the organiser'} about official security partner / sponsor packages, "
                         "and offer exhibitors booth security, high-value item guarding and alarm/CCTV for the show period.")
        steps.append(f"Follow up within 3 working days after {_fmt(r['end'])} and log contacts here.")

        out.append({
            "id": _id("ev", r["_norm"], r["start"]), "kind": "event",
            "name": r["name"], "start": r["start"].isoformat(), "end": r["end"].isoformat(),
            "month": r["start"].strftime("%Y-%m"), "months": _months(max(r["start"], month_start), r["end"]),
            "time": r.get("time", ""), "venue": venue, "area": area, "sectors": secs, "sector": primary,
            "access": access, "audience": r.get("audience", ""), "category": r.get("category", ""),
            "organiser": r.get("organiser", ""), "organiser_url": r.get("organiser_url", ""),
            "contact_phone": r.get("contact_phone", ""), "contact_email": r.get("contact_email", ""),
            "lead_types": leads or ["Prospect networking"], "who": who, "pitch": pitch, "actions": steps,
            "sources": r["sources"],
            "verification": "Official listing" + (f" · {len(r['sources'])} sources" if len(r["sources"]) > 1 else ""),
            "score": score, "level": _level(score, 7, 5), "thresholds": [7, 5], "reasons": reasons,
        })
    return out


